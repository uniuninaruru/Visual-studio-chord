import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryDirectory = resolve(scriptDirectory, "..");
const modelPath = join(repositoryDirectory, "models", "harmony-corpus-v1.json");
const artifactPath = join(
  repositoryDirectory,
  "frontend",
  "src",
  "generated",
  "harmonyStatistics.ts",
);
const artifactDirectory = dirname(artifactPath);
const expectedSha256 = "dfa28603b2aa0247abe5265a6975ae8267042a91e72e8c1ddd2221e2624209ae";
const expectedSource = {
  kind: "local-corpus",
  pop909SongCount: 909,
  sequenceCount: 1131,
  tokenCount: 93904,
};

function fail(message) {
  throw new Error(`Browser harmony statistics: ${message}`);
}

function assert(condition, message) {
  if (!condition) fail(message);
}

function validateModel(payload) {
  assert(payload && typeof payload === "object" && !Array.isArray(payload), "model must be an object");
  assert(payload.schemaVersion === 1, "unsupported schemaVersion");
  assert(payload.modelId === "harmony-corpus-ngram-v1", "unexpected modelId");
  assert(payload.modelVersion === "local-corpus-v1", "unexpected modelVersion");
  assert(payload.source && typeof payload.source === "object", "source metadata is required");
  for (const [key, value] of Object.entries(expectedSource)) {
    assert(payload.source[key] === value, `source.${key} must be ${value}`);
  }
  assert(payload.source.rawSongDataBundled === false, "raw source data must not be bundled");
  assert(typeof payload.source.pop909Commit === "string" && payload.source.pop909Commit.length > 0, "source commit is required");
  assert(typeof payload.source.pop909Repository === "string" && payload.source.pop909Repository.length > 0, "source repository is required");
  assert(payload.orders && typeof payload.orders === "object" && !Array.isArray(payload.orders), "orders are required");
  const orders = Object.keys(payload.orders).map(Number).sort((a, b) => a - b);
  assert(orders.length > 0 && orders.every((order, index) => order === index + 1), "orders must be contiguous from one");
  assert(orders.every((order) => order <= 5), "model order exceeds the supported source maximum");
  for (const order of orders) {
    const counts = payload.orders[String(order)];
    assert(counts && typeof counts === "object" && !Array.isArray(counts), `order ${order} must be an object`);
    assert(Object.keys(counts).length > 0, `order ${order} is empty`);
    for (const [gram, count] of Object.entries(counts)) {
      assert(typeof gram === "string" && gram.length > 0 && gram.length <= 128, `invalid gram in order ${order}`);
      assert(Number.isInteger(count) && count > 0, `invalid count for ${gram}`);
      const parts = gram.split(">");
      assert(parts.length === order && parts.every((part) => /^\d+:[A-Za-z0-9]+$/.test(part)), `invalid gram shape for ${gram}`);
    }
  }
  return orders;
}

function buildArtifact() {
  assert(existsSync(modelPath), `model not found at ${modelPath}`);
  const modelBytes = readFileSync(modelPath);
  const fullSourceSha256 = createHash("sha256").update(modelBytes).digest("hex");
  assert(fullSourceSha256 === expectedSha256, `full source SHA-256 mismatch (${fullSourceSha256})`);
  const payload = JSON.parse(modelBytes.toString("utf8"));
  const orders = validateModel(payload);
  const compactOrders = {};
  for (const order of [1, 2, 3]) compactOrders[String(order)] = payload.orders[String(order)];
  const provenance = {
    sourceKind: payload.source.kind,
    modelId: payload.modelId,
    modelVersion: payload.modelVersion,
    schemaVersion: payload.schemaVersion,
    sourceModelOrders: orders,
    browserOrders: [1, 2, 3],
    pop909Commit: payload.source.pop909Commit,
    pop909Repository: payload.source.pop909Repository,
    pop909SongCount: payload.source.pop909SongCount,
    sequenceCount: payload.source.sequenceCount,
    tokenCount: payload.source.tokenCount,
    fullSourceSha256,
    rawSongDataBundled: payload.source.rawSongDataBundled,
  };
  const json = JSON.stringify({ schemaVersion: 1, artifactVersion: 1, provenance, orders: compactOrders }, null, 2);
  return `/* Generated by scripts/build-browser-harmony-statistics.mjs. Do not edit by hand. */\nexport const HARMONY_STATISTICS_SNAPSHOT = ${json} as const;\n`;
}

const check = process.argv.includes("--check");
try {
  const artifact = buildArtifact();
  if (check) {
    assert(existsSync(artifactPath), `artifact not found at ${artifactPath}`);
    const current = readFileSync(artifactPath, "utf8");
    if (current !== artifact) fail("artifact is stale; run the stats:build script with npm or pnpm");
    console.log("Browser harmony statistics artifact is fresh.");
  } else {
    mkdirSync(artifactDirectory, { recursive: true });
    const temporaryPath = `${artifactPath}.${process.pid}.tmp`;
    writeFileSync(temporaryPath, artifact, "utf8");
    renameSync(temporaryPath, artifactPath);
    console.log(`Wrote ${artifactPath}`);
  }
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
